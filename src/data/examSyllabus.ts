export function isExamTopic(subjectId: string, chapterName: string): boolean {
  const list = EXAM_TOPICS_BY_SUBJECT[subjectId];
  if (!list || !chapterName) return false;
  const canonical = CHAPTER_ALIASES[chapterName] ?? chapterName;
  const target = normalize(canonical);
  return list.some((t) => normalize(t) === target);
}
